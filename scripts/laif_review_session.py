#!/usr/bin/env python3
"""Resumable human triage of a source-locked LAIF research evidence inventory.

Decisions record whether a passage is useful to inspect. They are not LAIF
criterion determinations, legal findings, or proof that a control operates.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import laif_research_report as research

SCHEMA = "laif.candidate-review.v1"
DECISIONS = {
    "a": "ACCEPT_FOR_REVIEW",
    "r": "REJECT_AS_IRRELEVANT",
    "n": "NEEDS_EVIDENCE",
    "o": "OUTSIDE_SCOPE",
}
IDENTITY_KEYS = (
    "dossier_sha256", "source_sha256", "extracted_text_sha256",
    "evidence_manifest_sha256", "renderer_sha256", "toolchain_fingerprint",
    "framework_source_sha256", "toolkit_source_sha256",
    "criteria_review_protocol_sha256",
)


class ReviewError(ValueError):
    pass


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Resume source-bound human review of research evidence candidates.")
    p.add_argument("dossier", type=Path, help="*.research_data.json generated by laif_research_report.py")
    p.add_argument("source", type=Path, help="the same original source used for that dossier")
    p.add_argument("--analyst", help="recorded reviewer name or ID; self-reported, not authenticated")
    p.add_argument("--session", type=Path, help="saved candidate-review JSON; defaults beside dossier")
    p.add_argument("--summary", action="store_true", help="show saved decisions without prompting")
    p.add_argument("--revisit", action="store_true", help="offer previously decided passages for revision")
    p.add_argument("--export", type=Path, help="write a new Markdown summary after review; refuses overwrite")
    return p


def _now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _safe_excerpt(value: str) -> str:
    return "".join(ch if ch.isprintable() else " " for ch in " ".join(value.split()))


def load_context(dossier_path: Path, source_path: Path) -> tuple[dict, dict]:
    dossier = research._read_json(dossier_path)
    if not isinstance(dossier, dict):
        raise ReviewError("Research dossier must be a JSON object")
    source = dossier.get("source")
    method = dossier.get("method")
    evidence = dossier.get("evidence")
    if (dossier.get("schema") != research.SCHEMA or not isinstance(source, dict)
            or not isinstance(method, dict) or not isinstance(evidence, list)):
        raise ReviewError("Expected a current LAIF research dossier, not another JSON file")
    if not source_path.is_file() or source_path.name != source.get("file_name"):
        raise ReviewError("Original source is missing or its file name differs from the dossier")
    if research.sha256_file(source_path) != source.get("source_sha256"):
        raise ReviewError("Original source bytes changed; generate a fresh dossier and recheck decisions")
    try:
        extraction = research._extract_local(source_path, source.get("extractor"))
    except (research.ResearchInputError, TypeError) as exc:
        raise ReviewError(f"Cannot reproduce dossier extraction: {exc}") from exc
    text = extraction.text
    if _sha(text.encode("utf-8")) != source.get("extracted_text_sha256"):
        raise ReviewError("Extracted text changed; generate a fresh dossier and recheck decisions")
    current_method = {
        "renderer_sha256": research.sha256_file(ROOT / "scripts/laif_research_report.py"),
        "toolchain_fingerprint": research.toolchain_fingerprint(),
        "framework_source_sha256": research.sha256_file(ROOT / "LAIF_v1.2.txt"),
        "toolkit_source_sha256": research.sha256_file(ROOT / "LAIF_Compliance_Toolkit.txt"),
        "criteria_review_protocol_sha256": research.sha256_file(ROOT / "scripts/laif_criteria_review.py"),
    }
    dossier_method = {
        "renderer_sha256": method.get("renderer_sha256"),
        "toolchain_fingerprint": method.get("internal_engine_fingerprint"),
        "framework_source_sha256": method.get("framework_source_sha256"),
        "toolkit_source_sha256": method.get("toolkit_source_sha256"),
        "criteria_review_protocol_sha256": method.get("criteria_review_protocol_sha256"),
    }
    if dossier_method != current_method:
        raise ReviewError("Dossier method identity is stale; regenerate it and recheck decisions")
    ids = set()
    for row in evidence:
        if not isinstance(row, dict) or not isinstance(row.get("evidence_id"), str):
            raise ReviewError("Dossier evidence record is malformed")
        eid = row["evidence_id"]
        start, end, quote = row.get("start_char"), row.get("end_char"), row.get("exact_quote")
        if (eid in ids or type(start) is not int or type(end) is not int
                or not isinstance(quote, str) or not 0 <= start < end <= len(text)
                or text[start:end] != quote):
            raise ReviewError(f"Dossier evidence span or identity is invalid: {eid}")
        ids.add(eid)
    if research._evidence_manifest_sha256(evidence) != dossier.get("evidence_manifest_sha256"):
        raise ReviewError("Dossier evidence manifest changed; regenerate it")
    identity = {
        "dossier_sha256": _sha(dossier_path.read_bytes()),
        "source_sha256": source["source_sha256"],
        "extracted_text_sha256": source["extracted_text_sha256"],
        "evidence_manifest_sha256": dossier["evidence_manifest_sha256"],
        **current_method,
    }
    return dossier, identity


def _session_path(dossier_path: Path, requested: Path | None) -> Path:
    if requested is not None:
        return requested.expanduser().resolve()
    name = dossier_path.name
    if not name.endswith(".research_data.json"):
        raise ReviewError("Use --session for a dossier without a .research_data.json name")
    return dossier_path.with_name(name.removesuffix(".research_data.json") + ".candidate_review.json")


def load_session(path: Path, identity: dict, dossier: dict, analyst: str | None) -> dict | None:
    if not path.exists():
        return None
    value = research._read_json(path)
    if not isinstance(value, dict):
        raise ReviewError("Saved review must be a JSON object")
    if value.get("schema") != SCHEMA or any(value.get(k) != identity[k] for k in IDENTITY_KEYS):
        raise ReviewError("Saved review does not match this source, extraction, dossier and method")
    if not isinstance(value.get("analyst_id"), str) or not value["analyst_id"].strip():
        raise ReviewError("Saved review has no attributed analyst")
    if analyst and analyst != value["analyst_id"]:
        raise ReviewError("Analyst ID differs from saved review; use a separate session")
    records = value.get("decisions")
    allowed = {row["evidence_id"]: row for row in dossier["evidence"]}
    if not isinstance(records, dict) or not set(records).issubset(allowed):
        raise ReviewError("Saved review contains unknown evidence IDs")
    for eid, record in records.items():
        row = allowed[eid]
        if (not isinstance(record, dict) or record.get("decision") not in DECISIONS.values()
                or not isinstance(record.get("note"), str) or not record["note"].strip()
                or record.get("quote_sha256") != _sha(row["exact_quote"].encode("utf-8"))):
            raise ReviewError(f"Saved decision is invalid or stale: {eid}")
    return value


def save_session(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    fd, temp_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, path)
    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)


def render_summary(dossier: dict, session: dict | None) -> str:
    decisions = session["decisions"] if session else {}
    label = research._md_text
    total = len(dossier["evidence"])
    lines = [
        "# Source candidate review",
        "",
        "**Status:** AUTHOR TRIAGE ONLY. These decisions concern retrieved passages, not LAIF criterion satisfaction, legal compliance or control operation.",
        f"**Source:** {label(dossier['source']['file_name'])}",
        f"**Original source SHA-256:** {dossier['source']['source_sha256']}",
        f"**Extracted text SHA-256:** {dossier['source']['extracted_text_sha256']}",
        f"**Evidence manifest SHA-256:** {dossier['evidence_manifest_sha256']}",
        f"**Dossier SHA-256:** {session['dossier_sha256'] if session else 'no saved session'}",
        f"**Analyst (self-reported):** {label(session['analyst_id']) if session else 'not recorded'}",
        f"**Progress:** {len(decisions)}/{total} passages decided; {total-len(decisions)} unresolved.",
        "",
        "## Passage decisions",
        "",
    ]
    for row in dossier["evidence"]:
        eid = row["evidence_id"]
        decision = decisions.get(eid)
        lines += [f"### {eid} — {label(decision['decision'] if decision else 'UNREVIEWED')}",
                  "", research._blockquote(row["exact_quote"]), "",
                  f"- Reviewer note: {label(decision['note']) if decision else 'No decision recorded.'}",
                  f"- Extracted-text line: {row.get('extracted_line', 'unknown')}",
                  "- Meaning: passage relevance only; inspect source context before substantive use.", ""]
    lines += ["## Next action", "",
              "Check unresolved passages and surrounding source context. Use the separate source-locked analyst template for any substantive finding; this candidate review is not an imported finding.", ""]
    return "\n".join(lines)


def run(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    dossier_path = args.dossier.expanduser().resolve()
    source_path = args.source.expanduser().resolve()
    try:
        session_path = _session_path(dossier_path, args.session)
        if session_path in (source_path, dossier_path):
            raise ReviewError("Session output must differ from source and dossier")
        dossier, identity = load_context(dossier_path, source_path)
        session = load_session(session_path, identity, dossier, args.analyst)
        loaded_session_sha = _sha(session_path.read_bytes()) if session is not None else None
        if not args.summary and dossier["evidence"]:
            if session is None:
                analyst = (args.analyst or input("Your analyst name or ID: ")).strip()
                if not analyst:
                    raise ReviewError("Analyst attribution is required")
                session = {"schema": SCHEMA, **identity, "analyst_id": analyst,
                           "created_at_utc": _now(), "updated_at_utc": _now(), "decisions": {}}
            for position, row in enumerate(dossier["evidence"], start=1):
                eid = row["evidence_id"]
                if eid in session["decisions"] and not args.revisit:
                    continue
                print(f"\nPassage {position}/{len(dossier['evidence'])} — {_safe_excerpt(eid)} — {_safe_excerpt(row['category'])}")
                print(f"  Extracted-text line: {row.get('extracted_line', 'unknown')}")
                print("  " + _safe_excerpt(row["exact_quote"]))
                if eid in session["decisions"]:
                    old = session["decisions"][eid]
                    print(f"  Saved: {old['decision']} — {_safe_excerpt(old['note'])}")
                while True:
                    print("  a=accept for review; r=irrelevant; n=needs evidence; o=outside scope")
                    choice = input("Decision [s=skip, q=quit]: ").strip().lower()
                    if choice in ("", "s", "q"):
                        break
                    if choice not in DECISIONS:
                        print("Unknown choice; try again for this passage, skip or quit.")
                        continue
                    note = input("Reason or next evidence needed: ").strip()
                    if not note:
                        print("A note is required; try again for this passage, skip or quit.")
                        continue
                    break
                if choice == "q":
                    break
                if choice in ("", "s"):
                    continue
                if (research.sha256_file(source_path) != identity["source_sha256"]
                        or _sha(dossier_path.read_bytes()) != identity["dossier_sha256"]):
                    raise ReviewError("Source or dossier changed during review; no new decision saved")
                current_session_sha = _sha(session_path.read_bytes()) if session_path.exists() else None
                if current_session_sha != loaded_session_sha:
                    raise ReviewError("Saved review changed during this run; reopen it before adding decisions")
                session["decisions"][eid] = {
                    "decision": DECISIONS[choice], "note": note,
                    "quote_sha256": _sha(row["exact_quote"].encode("utf-8")),
                    "recorded_at_utc": _now(),
                }
                session["updated_at_utc"] = _now()
                save_session(session_path, session)
                loaded_session_sha = _sha(session_path.read_bytes())
                print(f"Saved {eid} to {session_path}")
        summary = render_summary(dossier, session)
        if args.summary:
            print(summary)
        if args.export is not None:
            export = args.export.expanduser().resolve()
            if export in (source_path, dossier_path, session_path) or export.exists():
                raise ReviewError("Export path already exists or overlaps evidence; choose a new path")
            export.parent.mkdir(parents=True, exist_ok=True)
            with export.open("x", encoding="utf-8", newline="\n") as handle:
                handle.write(summary)
            print(f"Review summary exported: {export}")
        decided = len(session["decisions"]) if session else 0
        print(f"Review progress: {decided}/{len(dossier['evidence'])} passages decided; "
              f"{len(dossier['evidence'])-decided} unresolved.")
        if loaded_session_sha is not None:
            print(f"Saved review: {session_path}")
        else:
            print("No review file saved; record a decision and note to create one.")
        print("These are analyst passage decisions, not substantive LAIF findings.")
        return 0
    except (ReviewError, research.ResearchInputError, OSError, UnicodeError, TypeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="backslashreplace")
    try:
        raise SystemExit(run())
    except (KeyboardInterrupt, EOFError):
        print("\nStopped; completed passage decisions remain saved.", file=sys.stderr)
        raise SystemExit(2)
